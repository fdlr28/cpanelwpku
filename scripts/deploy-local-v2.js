// Deploys the full Eridanos v2 stack + the Provenalt router to a local node and writes the frontend config.
//   npx hardhat node                                     (terminal 1)
//   npx hardhat run scripts/deploy-local-v2.js --network localhost   (terminal 2)
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");
const { deployEridanos, deployAppRouter } = require("./lib/eridanos");
const { ASCEND_SHAPE, HYPE_START_TICK, USDC_START_TICK, buildPresetFromCurve } = require("./lib/presets");

async function main() {
  const { ethers, network } = hre;
  const [deployer, treasury, guardian, provenaltPayout] = await ethers.getSigners();
  const stack = await deployEridanos(hre, { deployer, owner: deployer.address, treasury: treasury.address, guardian: guardian.address });
  const { config, registry, core } = stack;

  // 6 decimals like real USDC: the USDC preset's start tick assumes it.
  const usdc = await (await ethers.getContractFactory("MockUSDC", deployer)).deploy(10n ** 12n * 10n ** 6n);
  const curve = buildPresetFromCurve(ASCEND_SHAPE);
  await (await config.setQuote(ethers.ZeroAddress, true)).wait();
  await (await config.addCurvePreset(ethers.ZeroAddress, HYPE_START_TICK, curve)).wait();
  await (await config.setQuote(await usdc.getAddress(), true)).wait();
  await (await config.addCurvePreset(await usdc.getAddress(), USDC_START_TICK, curve)).wait();
  await (await registry.setCore(await core.getAddress(), true)).wait();

  const router = await deployAppRouter(hre, stack, {
    deployer, owner: deployer.address, name: "Provenalt", uri: "https://provenalt.example",
    signer: ethers.ZeroAddress, payout: provenaltPayout.address,
    policy: { integratorBps: 3000, maxAllocBps: 2000, maxDevBuyBps: 1000, minCliff: 0, minDuration: 0, devBuyLock: 0 },
  });

  const addresses = {
    chainId: Number((await ethers.provider.getNetwork()).chainId),
    poolManager: await stack.pm.getAddress(),
    core: await core.getAddress(),
    router: await router.getAddress(),
    hook: await stack.hook.getAddress(),
    distributor: await stack.distributor.getAddress(),
    registry: await registry.getAddress(),
    config: await config.getAddress(),
    vault: await stack.vault.getAddress(),
    usdc: await usdc.getAddress(),
    deployBlock: 0,
  };
  console.log(addresses);
  fs.writeFileSync(path.join(__dirname, "..", "deployments", `${network.name}-v2.json`), JSON.stringify(addresses, null, 2));
  const cfg = `// Generated by scripts/deploy-local-v2.js
window.PROVENALT_CONFIG = ${JSON.stringify({ ...addresses, chainName: "Hardhat Local", rpcUrl: "http://127.0.0.1:8545", explorer: "", quoteSymbols: { [ethers.ZeroAddress]: "HYPE", [addresses.usdc]: "USDC" }, quoteDecimals: { [ethers.ZeroAddress]: 18, [addresses.usdc]: 6 } }, null, 2)};
`;
  fs.writeFileSync(path.join(__dirname, "..", "frontend", "config.local.js"), cfg);
  console.log("Wrote frontend/config.local.js");
}

main().catch((e) => { console.error(e); process.exitCode = 1; });
