// Full local stack: WHYPE + Uniswap V2 factory + launchpad, and writes frontend/config.local.js.
//   npx hardhat node             (terminal 1)
//   npm run deploy:local          (terminal 2)
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");
const UniswapV2Factory = require("@uniswap/v2-core/build/UniswapV2Factory.json");
const { buildCurve } = require("./curve");

async function main() {
  const { ethers } = hre;
  const [deployer] = await ethers.getSigners();

  const whype = await ethers.deployContract("WrappedNative");
  await whype.waitForDeployment();
  const factory = await new ethers.ContractFactory(UniswapV2Factory.abi, UniswapV2Factory.bytecode, deployer).deploy(
    deployer.address
  );
  await factory.waitForDeployment();

  const launchpad = await ethers.deployContract("ElysiumLaunchpad", [
    deployer.address,
    await factory.getAddress(),
    await whype.getAddress(),
    deployer.address,
    buildCurve({ virtualNative: process.env.VIRTUAL_NATIVE || "100" }),
  ]);
  await launchpad.waitForDeployment();
  const address = await launchpad.getAddress();

  console.log("WHYPE:           ", await whype.getAddress());
  console.log("UniswapV2Factory:", await factory.getAddress());
  console.log("ElysiumLaunchpad:", address);

  const cfg = `// Generated by scripts/deploy-local.js
window.LAUNCHPAD_CONFIG = {
  chainId: 31337,
  chainName: "Hardhat Local",
  rpcUrl: "http://127.0.0.1:8545",
  explorer: "",
  launchpad: "${address}",
  deployBlock: 0,
};
`;
  fs.writeFileSync(path.join(__dirname, "..", "frontend", "config.local.js"), cfg);
  console.log("Wrote frontend/config.local.js (load it instead of config.js for local testing)");
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
