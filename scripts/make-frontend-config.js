// Writes frontend/config.js from a deployment record, e.g. after the mainnet deploy:
//   node scripts/make-frontend-config.js deployments/elysiumMainnet-v2.json
// INDEXER_URL   indexer API for the site (default: the indexerUrl already in frontend/config.js; empty string = the
//               site reads the chain directly). The site ignores an indexer that serves another chain or core.
// Hidden tokens come from the deployment record (hiddenTokens), else from the current config or
// indexer/deployment.json when either is for the same core contract, else none. Chain name, RPC and explorer
// come from scripts/lib/networks.js.
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { ethers } = require("ethers");
const { networkOf } = require("./lib/networks");

const ROOT = path.join(__dirname, "..");
const src = process.argv[2];
if (!src) throw new Error("usage: node scripts/make-frontend-config.js deployments/<network>-v2.json");
const d = JSON.parse(fs.readFileSync(path.resolve(src), "utf8"));
const net = networkOf(d.chainId);
if (!net) throw new Error(`unknown chain ${d.chainId}`);
for (const k of ["core", "router", "hook", "distributor", "registry", "config", "vault", "poolManager", "infinityVault", "usdc", "deployBlock"]) {
  if (d[k] === undefined || d[k] === "") throw new Error(`${src}: missing ${k}`);
}

const dst = path.join(ROOT, "frontend", "config.js");
let current = {};
try {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(dst, "utf8"), sandbox);
  current = sandbox.window.PROVENALT_CONFIG || {};
} catch {}
const sameCore = String(current.core || "").toLowerCase() === String(d.core).toLowerCase();
const indexerUrl = process.env.INDEXER_URL !== undefined ? process.env.INDEXER_URL : current.indexerUrl || "";
let indexerDeployment = {};
try { indexerDeployment = JSON.parse(fs.readFileSync(path.join(ROOT, "indexer", "deployment.json"), "utf8")); } catch {}
const sameIndexerCore = String(indexerDeployment.core || "").toLowerCase() === String(d.core).toLowerCase();
const hidden = Array.isArray(d.hiddenTokens) && d.hiddenTokens.length ? d.hiddenTokens
  : sameCore && current.hiddenTokens?.length ? current.hiddenTokens
  : sameIndexerCore ? indexerDeployment.hiddenTokens || [] : [];

const a = (x) => ethers.getAddress(x);
const usdc = a(d.usdc);
const zero = ethers.ZeroAddress;
const when = (d.deployedAt || new Date().toISOString()).slice(0, 10);
const body = `// Provenalt frontend configuration for ${net.name} (chain ${d.chainId}), deployment of ${when} on PancakeSwap Infinity CL.
// Generated by scripts/make-frontend-config.js from ${path.relative(ROOT, path.resolve(src))}. For local testing,
// load config.local.js instead (generated by scripts/deploy-local-v2.js).
window.PROVENALT_CONFIG = window.PROVENALT_CONFIG || {
  chainId: ${Number(d.chainId)},
  chainName: ${JSON.stringify(net.name)},
  rpcUrl: ${JSON.stringify(net.publicRpc)},
  explorer: ${JSON.stringify(net.explorer)},
  poolManager: "${a(d.poolManager)}",
  infinityVault: "${a(d.infinityVault)}",
  core: "${a(d.core)}",
  router: "${a(d.router)}",
  hook: "${a(d.hook)}",
  distributor: "${a(d.distributor)}",
  registry: "${a(d.registry)}",
  config: "${a(d.config)}",
  vault: "${a(d.vault)}",
  usdc: "${usdc}",
  // Indexer API (indexer/, e.g. on Railway). Empty: the site reads the chain directly (no charts/trade history).
  indexerUrl: ${JSON.stringify(indexerUrl)},
  // Launches kept out of the token list (smoke tests). Their pages still open by direct link.
  hiddenTokens: [
${hidden.map((h) => `    "${a(h)}",\n`).join("")}  ],
  deployBlock: ${Number(d.deployBlock)},
  quoteSymbols: { "${zero}": "HYPE", "${usdc}": "USDC" },
  quoteDecimals: { "${zero}": 18, "${usdc}": 6 },
};
`;
fs.writeFileSync(dst, body);
console.log(`wrote frontend/config.js for ${net.name} (chain ${d.chainId}), core ${a(d.core)}, indexer ${indexerUrl || "(none)"}, ${hidden.length} hidden token(s)`);
